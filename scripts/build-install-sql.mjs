#!/usr/bin/env node
/**
 * Concatenates supabase/migrations/*.sql into supabase/install.sql.
 *
 * `supabase db push` is the right way to apply migrations, but it needs the
 * CLI on a computer. install.sql is the same thing as one paste into the
 * Supabase SQL editor, for setting the project up from a phone.
 *
 *   node scripts/build-install-sql.mjs
 *
 * Run it after changing anything in supabase/migrations/; `npm run build`
 * does not, so the check below is what keeps the two honest.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "supabase", "migrations");
const target = join(root, "supabase", "install.sql");

const files = readdirSync(dir)
  .filter((name) => name.endsWith(".sql"))
  .sort();

const header = `-- ===========================================================================
-- AGS Dismissal — complete schema, in one file
-- ---------------------------------------------------------------------------
-- GENERATED by scripts/build-install-sql.mjs. Do not edit: change the files in
-- supabase/migrations/ and run the script again.
--
-- Paste the whole file into the Supabase SQL editor and run it. It is the same
-- as \`supabase db push\`, for when there is no computer to run the CLI on. There
-- is nothing to fill in here.
--
-- Then run supabase/setup.sql, which creates the school, the classes and the
-- staff logins — that one has four values to edit at the top.
--
-- Run it ONCE. Migrations build on each other — the later ones change what the
-- earlier ones made — so replaying them is not the same as running them once.
-- The guard below stops a second run before it touches anything: if you see
-- "already installed", nothing was changed and you can go straight to
-- setup.sql.
--
-- Contains, in order:
${files.map((name) => `--   ${name}`).join("\n")}
-- ===========================================================================

`;

const guard = `-- ###########################################################################
-- Guard: is this a fresh project, a finished one, or an interrupted paste?
--
-- This file is ~70 KB. A phone or a flaky editor can cut a paste short, and
-- what that used to leave behind was unrecoverable: too far in to install
-- cleanly, not far enough to be usable. So:
--
--   • finished already  -> stop, change nothing
--   • cut short         -> clear the remains and install properly
--   • cut short, but a school exists -> stop; that is real data, not debris
--
-- The SQL editor runs the whole paste as one transaction, so stopping here
-- leaves the database exactly as it was.
-- ###########################################################################

do $install_guard$
declare
  v_schools bigint := 0;
begin
  -- promote_all_students() is the last thing this file creates, so its
  -- presence is what proves the whole paste arrived.
  if exists (
    select 1
      from pg_proc p
      join pg_namespace n on n.oid = p.pronamespace
     where n.nspname = 'public' and p.proname = 'promote_all_students'
  ) then
    raise exception
      'AGS Dismissal is already installed. Nothing was changed — carry on with supabase/setup.sql.'
      using errcode = '42P07';
  end if;

  if to_regclass('public.schools') is not null then
    execute 'select count(*) from public.schools' into v_schools;
    if v_schools > 0 then
      raise exception
        'AGS Dismissal is only half installed but already holds a school. Nothing was changed — do not re-run this file; ask before going further.'
        using errcode = '42P07';
    end if;
  end if;

  -- Debris from a cut-short paste. Nothing can have been stored in it.
  drop view if exists public.dismissal_queue cascade;
  drop table if exists
    public.dismissal_events,
    public.dismissal_requests,
    public.guardians,
    public.students,
    public.classrooms,
    public.profiles,
    public.schools
    cascade;
  drop type if exists
    public.user_role,
    public.user_role_legacy,
    public.dismissal_status,
    public.request_source,
    public.class_gender,
    public.section_scope
    cascade;
end
$install_guard$;

`;

const body = files
  .map((name) => {
    const sql = readFileSync(join(dir, name), "utf8").trimEnd();
    return `-- ###########################################################################\n-- ${name}\n-- ###########################################################################\n\n${sql}\n`;
  })
  .join("\n");

const footer = `
-- ###########################################################################
-- Proof the paste arrived in one piece.
--
-- The SQL editor shows the result of the last statement. If you do not see a
-- row saying "installed", the paste was cut short — copy the file again and
-- re-run it; the guard at the top will clear the partial install for you.
-- ###########################################################################

select
  'installed' as ags_dismissal,
  (select count(*) from pg_tables where schemaname = 'public') as tables,
  (select count(*) from pg_policies where schemaname = 'public') as policies,
  'Now run supabase/setup.sql' as next_step;
`;

const next = `${header}${guard}${body}${footer}`;

// `--check` fails instead of writing, so CI catches a migration that was added
// without regenerating this file.
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // Missing file: report it the same way as a stale one.
  }
  if (current !== next) {
    console.error(
      "supabase/install.sql is out of date. Run: node scripts/build-install-sql.mjs",
    );
    process.exit(1);
  }
  console.log(`supabase/install.sql is up to date (${files.length} migrations).`);
  process.exit(0);
}

writeFileSync(target, next);
console.log(`Wrote supabase/install.sql from ${files.length} migrations.`);
